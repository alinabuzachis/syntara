def _detach_audit_triggers() -> None:
    """Remove triggers and clear metadata.

    This function queries audit_table_metadata to discover which tables have
    triggers, then drops them. This approach works even if models have been
    renamed or removed since the migration was run.

    """
    conn = op.get_bind()

    # Query all auditable tables
    result = conn.execute(text("SELECT table_name FROM audit_table_metadata"))

    # Drop all triggers
    for row in result:
        table_name = row[0]
        # Table names from audit_table_metadata are from model __tablename__
        conn.execute(text(f"DROP TRIGGER IF EXISTS audit_trigger_{table_name} ON {table_name}"))

    # Clear metadata table
    conn.execute(text("TRUNCATE TABLE audit_table_metadata"))


def _create_audit_management_functions() -> None:
    """Create operational functions for managing audit triggers at runtime."""
    # ------------------------------------------------------------------
    # Returns a table showing which triggers are currently active
    # ------------------------------------------------------------------
    op.execute(
        """
        CREATE OR REPLACE FUNCTION audit_triggers_status()
        RETURNS TABLE (
            table_name text,
            model_name text,
            audit_level text,
            trigger_enabled boolean
        ) AS $$
        BEGIN
            RETURN QUERY
            SELECT
                atm.table_name,
                atm.model_name,
                atm.audit_level,
                EXISTS (
                    SELECT 1
                    FROM pg_trigger t
                    JOIN pg_class c ON t.tgrelid = c.oid
                    WHERE c.relname = atm.table_name
                      AND t.tgname = 'audit_trigger_' || atm.table_name
                      AND NOT t.tgisinternal
                ) AS trigger_enabled
            FROM audit_table_metadata atm
            ORDER BY atm.table_name;
        END;
        $$ LANGUAGE plpgsql;
        """
    )

    # ------------------------------------------------------------------
    # Disable all audit triggers while preserving metadata
    # ------------------------------------------------------------------
    op.execute(
        """
        CREATE OR REPLACE FUNCTION audit_triggers_disable()
        RETURNS TABLE (
            table_name text,
            status text
        ) AS $$
        DECLARE
            v_table_name text;
        BEGIN
            -- Disable triggers for all tables in metadata
            FOR v_table_name IN
                SELECT atm.table_name
                FROM audit_table_metadata atm
            LOOP
                -- Check if trigger exists before attempting to drop
                IF EXISTS (
                    SELECT 1
                    FROM pg_trigger t
                    JOIN pg_class c ON t.tgrelid = c.oid
                    WHERE c.relname = v_table_name
                      AND t.tgname = 'audit_trigger_' || v_table_name
                      AND NOT t.tgisinternal
                ) THEN
                    EXECUTE format('DROP TRIGGER audit_trigger_%I ON %I', v_table_name, v_table_name);
                    table_name := v_table_name;
                    status := 'disabled';
                    RETURN NEXT;
                ELSE
                    table_name := v_table_name;
                    status := 'already disabled';
                    RETURN NEXT;
                END IF;
            END LOOP;
        END;
        $$ LANGUAGE plpgsql;
        """
    )

    # ------------------------------------------------------------------
    # Re-enable all audit triggers based on existing metadata
    # ------------------------------------------------------------------
    op.execute(
        """
        CREATE OR REPLACE FUNCTION audit_triggers_enable()
        RETURNS TABLE (
            table_name text,
            status text
        ) AS $$
        DECLARE
            v_table_name text;
        BEGIN
            -- Enable triggers for all tables in metadata
            FOR v_table_name IN
                SELECT atm.table_name
                FROM audit_table_metadata atm
            LOOP
                -- Check if trigger already exists
                IF NOT EXISTS (
                    SELECT 1
                    FROM pg_trigger t
                    JOIN pg_class c ON t.tgrelid = c.oid
                    WHERE c.relname = v_table_name
                      AND t.tgname = 'audit_trigger_' || v_table_name
                      AND NOT t.tgisinternal
                ) THEN
                    EXECUTE format(
                        'CREATE TRIGGER audit_trigger_%I ' ||
                        'AFTER INSERT OR UPDATE OR DELETE ON %I ' ||
                        'FOR EACH ROW EXECUTE FUNCTION audit_crud_operation()',
                        v_table_name,
                        v_table_name
                    );
                    table_name := v_table_name;
                    status := 'enabled';
                    RETURN NEXT;
                ELSE
                    table_name := v_table_name;
                    status := 'already enabled';
                    RETURN NEXT;
                END IF;
            END LOOP;
        END;
        $$ LANGUAGE plpgsql;
        """
    )

    # ------------------------------------------------------------------
    # Disable audit trigger for a specific table
    # ------------------------------------------------------------------
    op.execute(
        """
        CREATE OR REPLACE FUNCTION audit_trigger_disable(p_table_name text)
        RETURNS text AS $$
        DECLARE
            v_exists boolean;
        BEGIN
            -- Verify table is in metadata
            SELECT EXISTS (
                SELECT 1
                FROM audit_table_metadata
                WHERE table_name = p_table_name
            ) INTO v_exists;

            IF NOT v_exists THEN
                RETURN 'error: table not in audit metadata';
            END IF;

            -- Check if trigger exists
            SELECT EXISTS (
                SELECT 1
                FROM pg_trigger t
                JOIN pg_class c ON t.tgrelid = c.oid
                WHERE c.relname = p_table_name
                  AND t.tgname = 'audit_trigger_' || p_table_name
                  AND NOT t.tgisinternal
            ) INTO v_exists;

            IF v_exists THEN
                EXECUTE format('DROP TRIGGER audit_trigger_%I ON %I', p_table_name, p_table_name);
                RETURN 'disabled';
            ELSE
                RETURN 'already disabled';
            END IF;
        END;
        $$ LANGUAGE plpgsql;
        """
    )

    # ------------------------------------------------------------------
    # Enable audit trigger for a specific table
    # ------------------------------------------------------------------
    op.execute(
        """
        CREATE OR REPLACE FUNCTION audit_trigger_enable(p_table_name text)
        RETURNS text AS $$
        DECLARE
            v_exists boolean;
        BEGIN
            -- Verify table is in metadata
            SELECT EXISTS (
                SELECT 1
                FROM audit_table_metadata
                WHERE table_name = p_table_name
            ) INTO v_exists;

            IF NOT v_exists THEN
                RETURN 'error: table not in audit metadata';
            END IF;

            -- Check if trigger already exists
            SELECT EXISTS (
                SELECT 1
                FROM pg_trigger t
                JOIN pg_class c ON t.tgrelid = c.oid
                WHERE c.relname = p_table_name
                  AND t.tgname = 'audit_trigger_' || p_table_name
                  AND NOT t.tgisinternal
            ) INTO v_exists;

            IF NOT v_exists THEN
                EXECUTE format(
                    'CREATE TRIGGER audit_trigger_%I ' ||
                    'AFTER INSERT OR UPDATE OR DELETE ON %I ' ||
                    'FOR EACH ROW EXECUTE FUNCTION audit_crud_operation()',
                    p_table_name,
                    p_table_name
                );
                RETURN 'enabled';
            ELSE
                RETURN 'already enabled';
            END IF;
        END;
        $$ LANGUAGE plpgsql;
        """
    )


